function Mark({ kind }: { kind: Kind }) {
  switch (kind) {
    case "github":
      return (
        <svg viewBox="0 0 24 24" width="26" height="26" fill="currentColor">
          <path d={GITHUB} />
        </svg>
      );
    case "instagram":
      return (
        <svg viewBox="0 0 24 24" width="22" height="22" fill="currentColor">
          <path d={INSTAGRAM} />
        </svg>
      );
    case "app-store":
      // Official Apple badge, black, unmodified.
      return <Image src="/images/brands/app-store-badge.svg" alt="" width="90" height="30" />;
    case "google-play":
      // Official Google Play badge; the PNG carries its own clear space, so 46px tall draws a ~30px badge.
      return <Image src="/images/brands/google-play-badge.png" alt="" width="119" height="46" />;
    case "linkedin":
      return <Image src="/images/brands/linkedin.svg" alt="" width="26" height="22" />;
    default:
      return <span className="lb-rocket-emoji">🚀</span>;
  }
}

export function LinkButton({ href, children }: { href: string; children: ReactNode }) {
  const kind = KINDS[new URL(href).hostname.replace(/^www\./, "")] ?? "rocket";
  return (
    <a href={href} target="_blank" rel="noreferrer" className={`lb lb-${kind} font-display text-sm font-bold`}>
      <span aria-hidden="true" className="lb-mark">
        <Mark kind={kind} />
      </span>
      <span className="lb-face">{children}</span>
    </a>
  );
}
